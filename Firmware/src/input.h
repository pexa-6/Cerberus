#pragma once
#include <cstdint>

// Кнопки подключены между GPIO и GND (INPUT_PULLUP), нажатие = LOW.
// ВАЖНО: на реальных кнопках подключай провода по диагонали (разные
// внутренние пары), иначе кнопка будет либо всегда "нажата", либо
// не будет реагировать вообще. Прозвони кнопку мультиметром перед
// пайкой, если не уверен в распиновке конкретной детали.

enum class Btn : uint8_t { Up, Down, Left, Right, Ok, Count };

namespace Input {

void begin();

// Опрашивает кнопки (дебаунс внутри). Возвращает true и заполняет
// 'out', если на этом вызове только что зафиксировано НАЖАТИЕ
// (переход из отпущенной в нажатую, после дебаунса). Если нажатий
// несколько в одном кадре, отдаёт по одной за вызов - поэтому
// Input::poll() стоит вызывать в цикле, пока не вернёт false.
bool poll(Btn& out);

// Текущее устойчивое (после дебаунса) состояние кнопки.
bool isDown(Btn b);

} // namespace Input
